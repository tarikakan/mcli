import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, it } from "node:test";
import { createDefaultConfig } from "../src/config.ts";
import {
  getEffectiveContextConfig,
  resolveMemoryScribe,
  runMemoryScribe,
  shouldAutoCompact,
} from "../src/memory-agent.ts";
import { createSession } from "../src/session.ts";
import type { AgentAvailability, AgentId } from "../src/types.ts";

function makeAvailability(available: AgentId[]): Record<AgentId, AgentAvailability> {
  const all: AgentId[] = ["claude", "codex", "agy", "deepseek", "kimi"];
  const map = {} as Record<AgentId, AgentAvailability>;
  for (const id of all) {
    const ok = available.includes(id);
    map[id] = {
      id,
      available: ok,
      mode: ok ? (id === "deepseek" ? "api" : "cli") : "missing",
      detail: ok ? "ready" : "missing",
    };
  }
  return map;
}

function createMockBin(dir: string, name: string, scriptBody: string): string {
  const filePath = path.join(dir, name);
  fs.writeFileSync(filePath, `#!/usr/bin/env node\n${scriptBody}\n`, { mode: 0o755 });
  return filePath;
}

describe("memory scribe agent (token saver)", () => {
  it("auto-selects cheapest available fast agent and supports explicit & local modes", () => {
    const config = createDefaultConfig();

    // Auto picks deepseek-chat first when available
    const auto1 = resolveMemoryScribe(config, makeAvailability(["claude", "codex", "deepseek"]));
    assert.equal(auto1.kind, "agent");
    assert.equal(auto1.agent, "deepseek");
    assert.equal(auto1.model, "deepseek-chat");

    // Auto falls back to claude:haiku when deepseek isn't configured
    const auto2 = resolveMemoryScribe(config, makeAvailability(["claude", "codex"]));
    assert.equal(auto2.kind, "agent");
    assert.equal(auto2.agent, "claude");
    assert.equal(auto2.model, "haiku");

    // Explicit local ($0 / 0 tokens)
    config.memory.agent = "local";
    const local = resolveMemoryScribe(config, makeAvailability(["claude", "deepseek"]));
    assert.equal(local.kind, "local");

    // Explicit agent + custom cheap model
    config.memory.agent = "agy";
    config.memory.model = "gemini-2.5-flash";
    const explicit = resolveMemoryScribe(config, makeAvailability(["agy"]));
    assert.equal(explicit.kind, "agent");
    assert.equal(explicit.agent, "agy");
    assert.equal(explicit.model, "gemini-2.5-flash");
  });

  it("enforces tighter context budgets for lean vs balanced vs full modes", () => {
    const config = createDefaultConfig();
    config.memory.mode = "lean";
    const lean = getEffectiveContextConfig(config);
    assert.equal(lean.maxContextChars, 6000);
    assert.equal(lean.maxContextTurns, 2);

    config.memory.mode = "balanced";
    const balanced = getEffectiveContextConfig(config);
    assert.equal(balanced.maxContextChars, 14000);

    config.memory.mode = "full";
    const full = getEffectiveContextConfig(config);
    assert.equal(full.maxContextChars, 24000);
  });

  it("triggers shouldAutoCompact only when unsummarized turns cross mode threshold", () => {
    const config = createDefaultConfig();
    config.memory.mode = "lean";
    config.memory.autoCompact = true;
    config.memory.autoCompactThresholdChars = 500;

    const session = createSession({ name: "heavy", cwd: "/tmp", activeAgent: "claude" });
    session.messages.push(
      { id: "u1", role: "user", content: "Turn 1", timestamp: "2026-01-01T00:00:00Z" },
      { id: "a1", role: "assistant", agent: "claude", content: "A".repeat(1200), timestamp: "2026-01-01T00:00:01Z" },
    );
    // Only 1 turn: lean keeps 1 turn verbatim -> should NOT auto-compact yet
    assert.equal(shouldAutoCompact(session, config), false);

    // Add 2nd turn + large content -> crosses lean threshold -> should auto-compact
    session.messages.push(
      { id: "u2", role: "user", content: "Turn 2", timestamp: "2026-01-01T00:00:02Z" },
      { id: "a2", role: "assistant", agent: "codex", content: "B".repeat(2500), timestamp: "2026-01-01T00:00:03Z" },
    );
    assert.equal(shouldAutoCompact(session, config), true);

    config.memory.autoCompact = false;
    assert.equal(shouldAutoCompact(session, config), false);
  });

  it("delegates compaction to the cheap Scribe agent (e.g. claude haiku) and reports token savings", async () => {
    const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "mcli-scribe-"));
    const prevHome = process.env.MCLI_HOME;
    process.env.MCLI_HOME = tmpDir;

    try {
      const mockClaude = createMockBin(
        tmpDir,
        "claude",
        `
        const args = process.argv.slice(2);
        const model = args[args.indexOf("--model") + 1];
        console.log(JSON.stringify({ type: "assistant", message: { content: [{ type: "text", text: "- Compact summary generated by " + model + ": heavy quark masses agreed." }] } }));
        `,
      );

      const config = createDefaultConfig();
      config.agents.claude = { command: mockClaude, outputMode: "stream-json" };
      config.memory.agent = "claude";
      config.memory.model = "haiku";
      config.memory.mode = "lean";

      const session = createSession({ name: "quarks", cwd: tmpDir, activeAgent: "codex" });
      session.messages.push(
        { id: "u1", role: "user", content: "Investigate heavy quarks", timestamp: "2026-01-01T00:00:00Z" },
        { id: "a1", role: "assistant", agent: "codex", model: "gpt-5.6-sol", content: "Long detailed analysis ".repeat(200), timestamp: "2026-01-01T00:00:01Z" },
        { id: "u2", role: "user", content: "Follow up on top quark", timestamp: "2026-01-01T00:00:02Z" },
        { id: "a2", role: "assistant", agent: "claude", model: "opus", content: "Latest reply", timestamp: "2026-01-01T00:00:03Z" },
      );

      const res = await runMemoryScribe({
        session,
        cwd: tmpDir,
        config,
        availability: makeAvailability(["claude", "codex"]),
      });

      assert.equal(res.compactedTurns, 1);
      assert.equal(res.mode, "agent");
      assert.match(res.scribeLabel, /Claude \(haiku\)/);
      assert.match(res.summary, /Compact summary generated by haiku/);
      assert.ok(res.estimatedTokensSaved > 500);
      assert.equal(session.summarizedUpTo, 2);
    } finally {
      if (prevHome === undefined) delete process.env.MCLI_HOME;
      else process.env.MCLI_HOME = prevHome;
      fs.rmSync(tmpDir, { recursive: true, force: true });
    }
  });
});
